def norm(s):
    s = unicodedata.normalize('NFD', s.lower())
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn')
    return re.sub(r'[^a-z0-9ñ]+', ' ', s).strip()

def claves(e):
    out = []
    for k in ('items', 'filas', 'nodos', 'callouts', 'pasos'):
        for it in e.get(k, []) or []:
            if 'clave' in it: out.append(it['clave'])
    if e['tipo'] == 'estructura':
        def walk(n):
            if 'clave' in n: out.append(n['clave'])
            for h in n.get('hijos', []): walk(h)
        walk(e['raiz'])
        for r in e['ramas']: walk(r)
    return out

