def R(x, y, w, h):
    return {'x': x, 'y': y, 'w': w, 'h': h}

def lado_auto(r, base):
    cx = (r['x'] + r['w'] / 2 - base['x']) / base['w']
    cy = (r['y'] + r['h'] / 2 - base['y']) / base['h']
    if r['w'] > base['w'] * 0.3:
        return 'abajo' if cy < 0.55 else 'arriba'
    if cx > 0.62:
        return 'izquierda'
    if cx < 0.38:
        return 'derecha'
    return 'abajo' if cy < 0.55 else 'arriba'

def zoom_de(r, base, minw=1150, minh=640):
    w = max(r['w'] * (1.5 if r['w'] < 1200 else 1.12), minw)
    h = max(r['h'] * 1.6, minh)
    cx, cy = r['x'] + r['w'] / 2, r['y'] + r['h'] / 2
    x = min(max(cx - w / 2, base['x']), base['x'] + base['w'] - w)
    y = min(max(cy - h / 2, base['y']), base['y'] + base['h'] - h)
    w = min(w, base['w']); h = min(h, base['h'])
    return R(round(max(x, base['x'])), round(max(y, base['y'])), round(w), round(h))

def P(id, img, titulo, narr, callouts=(), recorte=None, etiqueta=None, url=None, zooms=None, general=None, **kw):
    """Escena pantalla. callouts: (clave, rect, texto[, lado]); zooms: None = uno por callout;
    general: clave para volver al plano general al final."""
    base = recorte or R(0, 0, W, H)
    cs, zs = [], []
    for c in callouts:
        clave, rect, texto = c[0], c[1], c[2]
        lado = c[3] if len(c) > 3 and c[3] else lado_auto(rect, base)
        cs.append({'clave': clave, 'rect': rect, 'texto': texto, 'lado': lado})
        if zooms is None:
            zs.append({'clave': clave, 'rect': c[4] if len(c) > 4 else zoom_de(rect, base)})
    if zooms is not None:
        zs = [{'clave': z[0], 'rect': z[1]} if z[1] else {'clave': z[0]} for z in zooms]
    if general:
        zs.append({'clave': general})
    e = {'id': id, 'tipo': 'pantalla'}
    if etiqueta: e['etiqueta'] = etiqueta
    e.update({'titulo': titulo, 'url': url or URL, 'imagen': f'hd/{HD[img]}', 'tamano': {'w': W, 'h': H}})
    if recorte: e['recorte'] = recorte
    if zs: e['zooms'] = zs
    if cs: e['callouts'] = cs
    e['narracion'] = narr
    e.update(kw)
    return e

def S(id, tipo, narr, **kw):
    e = {'id': id, 'tipo': tipo}
    e.update(kw)
    e['narracion'] = narr
    return e

def cap(n, titulo, sub, narr):
    return {'id': f'cap{n}', 'tipo': 'capitulo', 'numero': n, 'titulo': titulo, 'subtitulo': sub, 'narracion': narr}

